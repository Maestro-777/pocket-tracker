  function translateTextNode(node) {
    const parent = node?.parentElement;
    if (!parent || shouldSkipElement(parent)) return;
    const current = String(node.nodeValue ?? '');
    let record = textRecords.get(node);
    if (!record || current !== record.rendered) {
      record = createTranslationRecord(current);
      textRecords.set(node, record);
    }
    const next = renderRecord(record, locale);
    if (next !== current) {
      node.nodeValue = next;
      record.rendered = next;
    }
  }

  function translateAttribute(element, attr) {
    if (shouldSkipElement(element) || !element.hasAttribute(attr)) return;
    const current = String(element.getAttribute(attr) ?? '');
    let records = attributeRecords.get(element);
    if (!records) {
      records = new Map();
      attributeRecords.set(element, records);
    }
    let record = records.get(attr);
    if (!record || current !== record.rendered) {
      record = createTranslationRecord(current);
      records.set(attr, record);
    }
    const next = renderRecord(record, locale);
    if (next !== current) {
      element.setAttribute(attr, next);
      record.rendered = next;
    }
  }

